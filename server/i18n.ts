const STRINGS: Record<Language, Record<TranslationKey, string>> = { en, sl };

export const TRANSLATION_KEYS = Object.keys(en) as TranslationKey[];

export function t(language: string | null | undefined, key: TranslationKey, params?: Record<string, string | number>): string {
	const dictionary = STRINGS[(language ?? DEFAULT_LANGUAGE) as Language] ?? STRINGS[DEFAULT_LANGUAGE];
	const template = dictionary[key] ?? STRINGS[DEFAULT_LANGUAGE][key] ?? key;

	if (!params) return template;

	return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match));
}

export function translator(language: string | null | undefined) {
	return (key: TranslationKey, params?: Record<string, string | number>) => t(language, key, params);
}
